#!/usr/bin/env python3
"""Apply left/right monitor workspace split live in Hyprland and persist to ~/.config/hypr/workspaces.lua."""

import json
import os
import subprocess
import sys

WORKSPACES_LUA = os.path.expanduser("~/.config/hypr/workspaces.lua")
TOTAL_WORKSPACES = 10


def hyprctl_json(args: list[str]):
    out = subprocess.check_output(["hyprctl", *args, "-j"], text=True)
    return json.loads(out)


def main() -> int:
    if len(sys.argv) < 2:
        return 1
    try:
        left_count = max(0, min(9, int(float(sys.argv[1]))))
    except ValueError:
        return 1

    monitors = hyprctl_json(["monitors"])
    if len(monitors) < 2:
        return 0

    monitors.sort(key=lambda m: (m.get("x", 0), m.get("id", 0)))
    left_mon = monitors[0]["name"]
    right_mon = monitors[-1]["name"]

    # Persist to ~/.config/hypr/workspaces.lua (sourced automatically by hyprland.lua)
    lines = ["-- Auto-generated by Quickshell Monitor Workspace Split\n"]
    if left_count == 0:
        lines.append("-- Shared workspaces (unpinned)\n")
    else:
        for i in range(1, TOTAL_WORKSPACES + 1):
            mon = left_mon if i <= left_count else right_mon
            if i == 1 or i == left_count + 1:
                lines.append(f'hl.workspace_rule({{ workspace = "{i}", monitor = "{mon}", default = true }})\n')
            else:
                lines.append(f'hl.workspace_rule({{ workspace = "{i}", monitor = "{mon}" }})\n')

    os.makedirs(os.path.dirname(WORKSPACES_LUA), exist_ok=True)
    with open(WORKSPACES_LUA, "w", encoding="utf-8") as f:
        f.writelines(lines)

    if left_count == 0:
        subprocess.run(["hyprctl", "reload"], check=False)
        return 0

    batch: list[str] = []
    for i in range(1, TOTAL_WORKSPACES + 1):
        mon = left_mon if i <= left_count else right_mon
        default_part = ",default:true" if (i == 1 or i == left_count + 1) else ""
        batch.append(f"keyword workspace {i},monitor:{mon}{default_part}")

    existing = hyprctl_json(["workspaces"])
    for ws in existing:
        wid = ws.get("id", -1)
        if 1 <= wid <= TOTAL_WORKSPACES:
            target = left_mon if wid <= left_count else right_mon
            if ws.get("monitor") != target:
                batch.append(f"dispatch moveworkspacetomonitor {wid} {target}")

    subprocess.run(["hyprctl", "--batch", " ; ".join(batch)], check=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
